from google import genai
from getpass import getpass

api_key = getpass("Enter your Gemini API Key: ")

client = genai.Client(api_key=api_key)

print("Gemini AI connected successfully!")

def study_assistant():

    print("================================")
    print("       AI STUDY ASSISTANT")
    print("================================")

    print("1. Ask a Question")
    print("2. Summarize Text")
    print("3. Explain a Concept")
    print("4. Generate a Quiz")
    print("5. Python Coding Help")

    choice = input("\nSelect an option (1-5): ")

    if choice == "1":
        prompt = input("Enter your question: ")

    elif choice == "2":
        text = input("Enter text to summarize: ")
        prompt = "Summarize this text into simple notes:\n" + text

    elif choice == "3":
        topic = input("Enter a topic: ")
        prompt = "Explain " + topic + " in beginner-friendly language."

    elif choice == "4":
        topic = input("Enter a topic for the quiz: ")
        prompt = "Generate 5 multiple-choice questions about " + topic

    elif choice == "5":
        question = input("Enter your Python coding question: ")
        prompt = "Help me understand and solve this Python question: " + question

    else:
        print("Invalid option. Please select 1-5.")
        return

    print("\nGenerating AI Response...\n")

    response = client.models.generate_content(
        model="gemini-3.8-flash",
        contents=prompt
    )

    print("===== AI RESPONSE =====")
    print(response.text)


study_assistant()